class Adafruit_GFX {
protected:
    int16_t _width, _height;
    std::vector<uint8_t> _buffer;
    int16_t _cursor_x = 0, _cursor_y = 0;
    uint8_t _text_size = 1;
    uint16_t _text_color = 1;

public:
    Adafruit_GFX(int16_t w, int16_t h) : _width(w), _height(h), _buffer(w * h, 0) {}

    void setTextSize(uint8_t s) { _text_size = (s > 0) ? s : 1; }
    void setTextColor(uint16_t c) { _text_color = (c > 0) ? 1 : 0; }
    void setCursor(int16_t x, int16_t y) { _cursor_x = x; _cursor_y = y; }

    void write(uint8_t c) {
        if (c == '\n') {
            _cursor_x = 0;
            _cursor_y += _text_size * 8;
        } else if (c >= 32 && c <= 126) {
            if (_cursor_x > _width - _text_size * 6) {
                _cursor_x = 0;
                _cursor_y += _text_size * 8;
            }
            drawChar(_cursor_x, _cursor_y, c, _text_color, _text_size);
            _cursor_x += _text_size * 6;
        }
    }

    void drawChar(int16_t x, int16_t y, unsigned char c, uint16_t color, uint8_t size) {
        if (c < 32 || c > 127) return;
        for (int8_t i = 0; i < 5; i++) {
            uint8_t line = font[(c - 32) * 5 + i];
            for (int8_t j = 0; j < 8; j++) {
                if (line & 0x1) {
                    if (size == 1) drawPixel(x + i, y + j, color);
                    else fillRect(x + i * size, y + j * size, size, size, color);
                }
                line >>= 1;
            }
        }
    }

    void print(const char* s) { while(*s) write(*s++); }
    void print(std::string s) { for(char c : s) write(c); }
    void print(float f, int p = 2) { char buf[32]; snprintf(buf, sizeof(buf), "%.*f", p, f); print(buf); }
    void print(int i) { char buf[32]; snprintf(buf, sizeof(buf), "%d", i); print(buf); }
    void println(const char* s) { print(s); write('\n'); }
    void println(float f, int p = 2) { print(f, p); write('\n'); }
    void println(int i) { print(i); write('\n'); }
    void println() { write('\n'); }

    virtual void drawPixel(int16_t x, int16_t y, uint16_t color) {
        if (x < 0 || x >= _width || y < 0 || y >= _height) return;
        _buffer[y * _width + x] = (color > 0) ? 1 : 0;
    }

    void drawLine(int16_t x0, int16_t y0, int16_t x1, int16_t y1, uint16_t color) {
        int dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
        int dy = -abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
        int err = dx + dy, e2;
        for (;;) {
            drawPixel(x0, y0, color);
            if (x0 == x1 && y0 == y1) break;
            e2 = 2 * err;
            if (e2 >= dy) { err += dy; x0 += sx; }
            if (e2 <= dx) { err += dx; y0 += sy; }
        }
    }

    void drawRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
        for (int16_t i = x; i < x + w; i++) { drawPixel(i, y, color); drawPixel(i, y + h - 1, color); }
        for (int16_t i = y; i < y + h; i++) { drawPixel(x, i, color); drawPixel(x + w - 1, i, color); }
    }

    void fillRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
        for (int16_t i = x; i < x + w; i++)
            for (int16_t j = y; j < y + h; j++)
                drawPixel(i, j, color);
    }

    void drawFastVLine(int16_t x, int16_t y, int16_t h, uint16_t color) {
        if (h < 0) { y += h; h = -h; }
        for (int16_t i = y; i < y + h; i++) drawPixel(x, i, color);
    }

    void getTextBounds(const char* s, int16_t x, int16_t y, int16_t* x1, int16_t* y1, uint16_t* w, uint16_t* h) {
        *x1 = x; *y1 = y;
        *w = strlen(s) * 6 * _text_size;
        *h = 8 * _text_size;
    }

    void ssd1306_command(uint8_t c) {}

    void savePBM(const char* filename) {
        std::ofstream f(filename);
        f << "P1\n" << _width << " " << _height << "\n";
        for (int j = 0; j < _height; j++) {
            for (int i = 0; i < _width; i++) {
                f << (int)_buffer[j * _width + i] << (i == _width - 1 ? "" : " ");
            }
            f << "\n";
        }
        f.close();
    }
};

